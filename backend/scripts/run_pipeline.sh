#!/bin/bash
# ==============================================================================
# みんなの安全マップ - オープンデータ & GIS ETL パイプライン実行スクリプト (Fさん用)
# ==============================================================================
set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

echo "=========================================================="
echo "🗺️  みんなの安全マップ - オープンデータ パイプライン開始"
echo "=========================================================="

cd "${BACKEND_DIR}"

echo ""
echo "📥 [1/2] オープンデータを hazards.json へインポート中..."
npx ts-node scripts/import_opendata.ts

echo ""
echo "🗄️  [2/2] PostGIS用 SQL/ETL スクリプトを生成中..."
npx ts-node scripts/etl_postgis.ts

echo ""
echo "=========================================================="
echo "✅ オープンデータ パイプラインが正常に完了しました！"
echo "=========================================================="
